pub fn generate_markdown_report(
    components: &[ClusterComponent],
    items: &[EmbeddedItem],
    model_name: &str,
    graph_silhouette: f32,
    agglo_k: usize,
    agglo_silhouette: f32,
    ari_score: f32,
    output_path: &Path,
) -> Result<()> {
    let mut md = String::new();

    md.push_str("# EarlyBird Application Core – Semantic Architecture Proposal\n\n");
    md.push_str("> **Generated by Semantic Project Architecture Pipeline**  \n");
    md.push_str(&format!("> **Embedding Model:** `{}`  \n", model_name));
    md.push_str("> **Clustering Strategy:** Qdrant HNSW Distance Matrix API + Louvain Modularity Community Detection  \n\n");

    md.push_str("---\n\n");

    md.push_str("## 1. Executive Summary\n\n");
    md.push_str("This architecture proposal derives the application core components for the **Early Bird Management System (EBMS)** directly from the semantic topology of its functional requirements and domain rules. By embedding the normalized requirements into a high-dimensional vector space and clustering them in the Qdrant vector database, cohesive clusters of business capabilities naturally emerge.\n\n");
    md.push_str("Each cluster forms a candidate cohesive **application core component** (or adapter boundary), minimizing cross-component conceptual coupling while maximizing internal cohesion.\n\n");

    md.push_str("### Architecture Overview Table\n\n");
    md.push_str("| Cluster | Component Name | Cohesion | Requirements | Original PDF IDs | Distinguishing Keywords |\n");
    md.push_str("|---|---|---|---|---|---|\n");
    for comp in components {
        let pdf_ids_str = comp
            .source_pdf_ids
            .iter()
            .map(|id| id.to_string())
            .collect::<Vec<_>>()
            .join(", ");
        let keywords_str = comp.keywords.join(", ");
        md.push_str(&format!(
            "| **C{}** | **{}** | {:.2} | {} reqs | {} | `{}` |\n",
            comp.cluster_id + 1,
            comp.name,
            comp.cohesion,
            comp.requirement_ids.len(),
            pdf_ids_str,
            keywords_str
        ));
    }
    md.push_str("\n---\n\n");

    md.push_str("## 2. Clustering Method Evaluation & Verification\n\n");
    md.push_str("To ensure the proposed component boundaries are robust and not an artifact of a single algorithm, we evaluated the Qdrant server-side graph clustering against classical Hierarchical Agglomerative Clustering:\n\n");

    md.push_str("| Clustering Method | Number of Clusters ($k$) | Mean Silhouette Score | Algorithm Notes |\n");
    md.push_str("|---|---|---|---|\n");
    md.push_str(&format!(
        "| **Qdrant Distance Matrix + Louvain (Primary)** | **{}** | **{:.3}** | Emergent modularity on HNSW kNN topology |\n",
        components.len(),
        graph_silhouette
    ));
    md.push_str(&format!(
        "| **Agglomerative (Average Linkage)** | **{}** | **{:.3}** | Global average-linkage tree cut at optimal $k$ |\n",
        agglo_k,
        agglo_silhouette
    ));
    md.push_str("\n");
    md.push_str(&format!(
        "**Adjusted Rand Index (ARI) between methods: `{:.3}`** (indicates strong structural alignment across differing clustering mechanics).\n\n",
        ari_score
    ));

    md.push_str("---\n\n");

    md.push_str("## 3. Detailed Component Specifications\n\n");

    let item_map: HashMap<&str, &EmbeddedItem> = items.iter().map(|it| (it.id.as_str(), it)).collect();

    for comp in components {
        md.push_str(&format!("### Component {}: {}\n\n", comp.cluster_id + 1, comp.name));
        md.push_str(&format!("- **Primary Responsibility:** {}\n", comp.responsibility));
        md.push_str(&format!("- **Internal Cohesion Score:** `{:.2}`\n", comp.cohesion));
        md.push_str(&format!("- **Semantic Keywords:** `{}`\n", comp.keywords.join(", ")));
        md.push_str(&format!(
            "- **Representative Medoid Requirement:** `[{}]` *\"{}\"*\n\n",
            comp.medoid_id, comp.medoid_text
        ));

        md.push_str("#### Allocated Requirements\n\n");
        md.push_str("| Req ID | Kind | PDF # | Requirement Text |\n");
        md.push_str("|---|---|---|---|\n");

        for req_id in &comp.requirement_ids {
            if let Some(item) = item_map.get(req_id.as_str()) {
                let pdf_str = item
                    .source_ids
                    .iter()
                    .map(|id| id.to_string())
                    .collect::<Vec<_>>()
                    .join(", ");
                md.push_str(&format!(
                    "| `{}` | {} | {} | {} |\n",
                    item.id, item.kind, pdf_str, item.text
                ));
            }
        }
        md.push_str("\n");
    }

    md.push_str("---\n\n");

    md.push_str("## 4. Architectural Analysis: The \"Almost\" in Clustering\n\n");
    md.push_str("Clustering groups requirements by **semantic cohesion** (what belongs together). However, software architecture also requires classifying components into **architectural archetypes, layers, and dependency directions**:\n\n");

    md.push_str("### 1. Core Domain Services (Application Core)\n");
    md.push_str("- **Product Catalog & Search:** Core entity model for products, composite prepackages, units, and pricing rules.\n");
    md.push_str("- **Shopping Cart & Order Placement:** Manages order construction, shopping carts, blueprint cloning, and checksum validation.\n");
    md.push_str("- **Order Lifecycle & Cancellation:** Finite state machine managing status progression (Placed -> Assembled -> Delivering -> Completed/Cancelled).\n");
    md.push_str("- **Customer Identity & Account Management:** Customer entity, checksum verification, blacklist lookup, and address mapping.\n\n");

    md.push_str("### 2. Fulfilment & Operations\n");
    md.push_str("- **Fulfilment & Packing Operations:** Internal operational workflows for packing staff, paper bag labels, and duplicate invoice generation.\n");
    md.push_str("- **Delivery Logistics & Routing:** Itinerary route planning and field delivery confirmation.\n\n");

    md.push_str("### 3. Adapters & External Gateways (Hexagonal Architecture Ports)\n");
    md.push_str("- **SMS Ordering Gateway (Inbound Primary Adapter):** Receives SMS text messages, parses string syntax (`C... W... P...`), and delegates to Order Placement or Cancellation.\n");
    md.push_str("- **External Payment Integration (Outbound Secondary Adapter):** Listens for order packaging completion events and transmits expected-payment interface records to the external billing system.\n");
    md.push_str("- **Management Reporting (Outbound / Reporting Facet):** Scheduled nightly batch job querying order and staff metrics for management.\n");

    if let Some(parent) = output_path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(output_path, md)
        .with_context(|| format!("Failed to write report to {:?}", output_path))?;

    println!("Generated architecture proposal report at {:?}", output_path);
    Ok(())
}

/// Simple 2D projection via power-iteration PCA
pub fn pca_2d(points: &[Vec<f32>]) -> Vec<(f32, f32)> {
    let n = points.len();
    if n == 0 {
        return Vec::new();
    }
    let d = points[0].len();

    // 1. Mean center
    let mut mean = vec![0.0f32; d];
    for p in points {
        for j in 0..d {
            mean[j] += p[j];
        }
    }
    for j in 0..d {
        mean[j] /= n as f32;
    }

    let centered: Vec<Vec<f32>> = points
        .iter()
        .map(|p| p.iter().zip(&mean).map(|(x, m)| x - m).collect())
        .collect();

    // 2. Power iteration for 1st eigenvector
    let mut v1 = vec![1.0f32; d];
    for _ in 0..30 {
        let mut next_v = vec![0.0f32; d];
        for row in &centered {
            let dot: f32 = row.iter().zip(&v1).map(|(a, b)| a * b).sum();
            for j in 0..d {
                next_v[j] += dot * row[j];
            }
        }
        let norm = next_v.iter().map(|x| x * x).sum::<f32>().sqrt();
        if norm > 1e-12 {
            for j in 0..d {
                v1[j] = next_v[j] / norm;
            }
        }
    }

    // 3. Deflate and power iteration for 2nd eigenvector
    let mut v2 = vec![-1.0f32; d];
    for _ in 0..30 {
        let mut next_v = vec![0.0f32; d];
        for row in &centered {
            let dot1: f32 = row.iter().zip(&v1).map(|(a, b)| a * b).sum();
            // deflated row
            let deflated: Vec<f32> = row.iter().zip(&v1).map(|(r, v)| r - dot1 * v).collect();
            let dot2: f32 = deflated.iter().zip(&v2).map(|(a, b)| a * b).sum();
            for j in 0..d {
                next_v[j] += dot2 * deflated[j];
            }
        }
        let norm = next_v.iter().map(|x| x * x).sum::<f32>().sqrt();
        if norm > 1e-12 {
            for j in 0..d {
                v2[j] = next_v[j] / norm;
            }
        }
    }

    // Project each point to (x, y)
    centered
        .iter()
        .map(|p| {
            let x: f32 = p.iter().zip(&v1).map(|(a, b)| a * b).sum();
            let y: f32 = p.iter().zip(&v2).map(|(a, b)| a * b).sum();
            (x, y)
        })
        .collect()
}

pub fn generate_cluster_svg(
    items: &[EmbeddedItem],
    labels: &[usize],
    components: &[ClusterComponent],
    output_path: &Path,
) -> Result<()> {
    let embeddings: Vec<Vec<f32>> = items.iter().map(|it| it.embedding.clone()).collect();
    let points_2d = pca_2d(&embeddings);

    if let Some(parent) = output_path.parent() {
        std::fs::create_dir_all(parent)?;
    }

    let root = SVGBackend::new(output_path, (1100, 750)).into_drawing_area();
    root.fill(&WHITE)?;

    let mut min_x = f32::INFINITY;
    let mut max_x = -f32::INFINITY;
    let mut min_y = f32::INFINITY;
    let mut max_y = -f32::INFINITY;

    for &(x, y) in &points_2d {
        if x < min_x { min_x = x; }
        if x > max_x { max_x = x; }
        if y < min_y { min_y = y; }
        if y > max_y { max_y = y; }
    }

    let pad_x = (max_x - min_x) * 0.12;
    let pad_y = (max_y - min_y) * 0.12;

    let mut chart = ChartBuilder::on(&root)
        .caption(
            "EarlyBird Requirements: 2D Embedding Projection & Architecture Clusters",
            ("sans-serif", 24).into_font(),
        )
        .margin(20)
        .x_label_area_size(40)
        .y_label_area_size(40)
        .build_cartesian_2d((min_x - pad_x)..(max_x + pad_x), (min_y - pad_y)..(max_y + pad_y))?;

    chart
        .configure_mesh()
        .x_desc("Principal Component 1")
        .y_desc("Principal Component 2")
        .draw()?;

    let palette = [
        RGBColor(31, 119, 180),  // blue
        RGBColor(255, 127, 14),  // orange
        RGBColor(44, 160, 44),   // green
        RGBColor(214, 39, 40),   // red
        RGBColor(148, 103, 189), // purple
        RGBColor(140, 86, 75),   // brown
        RGBColor(227, 119, 194), // pink
        RGBColor(127, 127, 127), // gray
        RGBColor(188, 189, 34),  // olive
        RGBColor(23, 190, 207),  // cyan
    ];

    let comp_name_map: HashMap<usize, &str> = components
        .iter()
        .map(|c| (c.cluster_id, c.name.as_str()))
        .collect();

    // Group points by cluster
    let mut clusters: HashMap<usize, Vec<(usize, (f32, f32))>> = HashMap::new();
    for (idx, &(x, y)) in points_2d.iter().enumerate() {
        let lbl = labels[idx];
        clusters.entry(lbl).or_default().push((idx, (x, y)));
    }

    let mut sorted_cids: Vec<usize> = clusters.keys().copied().collect();
    sorted_cids.sort_unstable();

    for cid in sorted_cids {
        let color = palette[cid % palette.len()];
        let comp_name = comp_name_map.get(&cid).copied().unwrap_or("Component");
        let cluster_points = &clusters[&cid];

        let series_points: Vec<(f32, f32)> = cluster_points.iter().map(|(_, pt)| *pt).collect();

        chart
            .draw_series(
                series_points
                    .iter()
                    .map(|&(x, y)| Circle::new((x, y), 6, ShapeStyle::from(&color).filled())),
            )?
            .label(format!("C{}: {}", cid + 1, comp_name))
            .legend(move |(x, y)| Circle::new((x + 10, y), 5, ShapeStyle::from(&color).filled()));

        // Point labels (Req ID)
        for &(pt_idx, (x, y)) in cluster_points {
            let label_text = items[pt_idx].id.clone();
            chart.draw_series(std::iter::once(Text::new(
                label_text,
                (x + 0.015 * pad_x, y + 0.015 * pad_y),
                ("sans-serif", 10).into_font().color(&color),
            )))?;
        }
    }

    chart
        .configure_series_labels()
        .background_style(&WHITE.mix(0.85))
        .border_style(&BLACK.mix(0.2))
        .position(SeriesLabelPosition::UpperRight)
        .draw()?;

    root.present()?;
    println!("Generated 2D cluster visualization at {:?}", output_path);
    Ok(())
}
